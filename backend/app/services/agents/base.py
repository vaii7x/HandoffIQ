"""Abstract interfaces and typed communication models for multi-agent pipeline stages."""

from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional
from uuid import UUID
from pydantic import BaseModel, Field

from app.models.artifact import CodeArtifact
from app.models.handoff import Handoff, ValidationIssue
from app.models.requirement import Requirement
from app.models.test_result import TestResult


# ============================================================================
# 1. Researcher Models & Interface
# ============================================================================

class ResearchInput(BaseModel):
    """Input payload delivered to the Researcher agent."""

    task_id: UUID
    original_request: str
    requirements: List[Requirement] = Field(default_factory=list)


class ResearchOutput(BaseModel):
    """Structured architectural findings and context emitted by Researcher."""

    summary: str = Field(description="Executive summary of architecture and specifications")
    handoff_payload: Dict[str, Any] = Field(
        description="Structured context passed to downstream agents"
    )
    requirement_ids: List[str] = Field(
        description="List of canonical requirement IDs addressed in this research"
    )


class ResearcherService(ABC):
    """Interface for the Researcher agent."""

    @property
    @abstractmethod
    def name(self) -> str:
        pass

    @abstractmethod
    async def execute(self, input_data: ResearchInput) -> ResearchOutput:
        pass


# ============================================================================
# 2. ContextMap Models & Interface
# ============================================================================

class ContextMapInput(BaseModel):
    """Input provided to assemble context mapping between Researcher and Coder."""

    task_id: UUID
    requirements: List[Requirement]
    validated_handoff: Handoff


class ContextMapOutput(BaseModel):
    """Formatted context map isolating global constraints and per-requirement files."""

    global_context: Dict[str, Any] = Field(default_factory=dict)
    requirement_mappings: Dict[str, Any] = Field(default_factory=dict)


class ContextMapService(ABC):
    """Interface coordinating structured context projection."""

    @property
    @abstractmethod
    def name(self) -> str:
        pass

    @abstractmethod
    async def create_context_map(self, input_data: ContextMapInput) -> ContextMapOutput:
        pass


