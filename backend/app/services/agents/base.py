# ============================================================================
# 6. Recovery Decision Models & Interface
# ============================================================================

class RecoveryInput(BaseModel):
    """Input supplied to decide whether an automated recovery attempt should be made."""

    task_id: UUID
    requirements: List[Requirement]
    failed_tests: List[TestResult] = Field(default_factory=list)
    review_issues: List[ValidationIssue] = Field(default_factory=list)
    attempt_number: int = 1


class RecoveryDecision(BaseModel):
    """Decision on whether to retry a failed workflow stage."""

    should_retry: bool
    retry_stage: Optional[str] = None
    repair_summary: str = Field(default="")


class RecoveryDecisionService(ABC):
    """Interface evaluating workflow self-healing / repair loops."""

    @property
    @abstractmethod
    def name(self) -> str:
        pass

    @abstractmethod
    async def evaluate(self, input_data: RecoveryInput) -> RecoveryDecision:
        pass
